import assert from 'node:assert/strict';
import fs from 'node:fs';
import {DEFAULT_LESSONS,defaultLessonSlots,schedule,atTime} from '../src/engine.mjs';
const raw=JSON.parse(fs.readFileSync(new URL('../skill/tagesablauf/references/LEKTIONEN.json',import.meta.url),'utf8'));
assert.deepEqual(DEFAULT_LESSONS,raw.lessons);
assert.equal(DEFAULT_LESSONS.length,10);
assert.deepEqual(defaultLessonSlots([9,10]),[{start:'16:25',end:'17:10'},{start:'17:15',end:'18:00'}]);
const whole=schedule({slots:defaultLessonSlots(),activities:[{id:'a',duration:451}]});
assert.equal(whole.available,450);assert.equal(whole.start,495);assert.equal(whole.end,1080);assert.equal(whole.overflow,1);
assert.equal(whole.segments.filter(s=>s.kind==='fixed-break').reduce((n,s)=>n+s.duration,0),135);
const morning=schedule({slots:defaultLessonSlots([1,2]),activities:[{id:'a',duration:60}]});
assert.equal(morning.activities[0].segments.length,1);
assert.equal(morning.activities[0].end,555);
assert.equal(morning.segments.some(s=>s.kind==='fixed-break'),false);
const lunch=schedule({slots:defaultLessonSlots([5,6]),activities:[{id:'a',duration:60}]});
assert.deepEqual(lunch.activities[0].segments.map(s=>[s.start,s.end]),[[715,760],[825,840]]);
assert.equal(atTime(lunch,800).kind,'fixed-break');
const copy=defaultLessonSlots();copy[0].start='00:00';assert.equal(DEFAULT_LESSONS[0].start,'08:15');
assert.throws(()=>defaultLessonSlots([11]),/Unbekannte/);
console.log('Passed: all ten lesson times, continuous lessons 1–2, 65-minute lunch break, 450 working minutes, one-minute overflow and isolated plan copies.');
